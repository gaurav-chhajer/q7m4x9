#!/usr/bin/env python3
"""Generate SYNTHETIC wind data so the app runs before you ingest the real Elexon data.

It is flagged `synthetic: true`, and the UI shows a banner while it is in use.
Hourly targets with forecasts issued every 3 hours, to mirror the shape of the real WINDFOR data.
Never present these numbers as real.   Usage: python scripts/make_sample.py
"""
import csv
import json
import math
import random
from datetime import date, datetime, time, timedelta, timezone
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "backend" / "data" / "sample"
UTC = timezone.utc
START, END = date(2026, 1, 2), date(2026, 2, 1)
CAPACITY = 14500.0
rng = random.Random(42)


def iso(dt):
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


t0 = datetime.combine(START - timedelta(days=3), time(0), tzinfo=UTC)
n_slots = (END - START).days * 48 + 48 + 3 * 48 + 96
phases = [rng.uniform(0, 6.28) for _ in range(3)]
noise, truth = 0.0, {}
for i in range(n_slots):
    t = t0 + timedelta(minutes=30 * i)
    noise = 0.985 * noise + rng.gauss(0, 0.012)
    idx = 0.42 + 0.22 * math.sin(i / 48 / 2.3 + phases[0]) + 0.12 * math.sin(i / 48 / 0.9 + phases[1]) \
        + 0.04 * math.sin(i / 48 * 6.28 + phases[2]) + noise
    truth[t] = max(0.03, min(0.95, idx)) * CAPACITY

slot_range = [datetime.combine(START, time(0), tzinfo=UTC) + timedelta(minutes=30 * i)
              for i in range((END - START).days * 48 + 48)]
persist = {t: rng.gauss(0, 1) for t in slot_range}          # unforecastable part, shared by all issuances of a target

OUT.mkdir(parents=True, exist_ok=True)
with (OUT / "actuals.csv").open("w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["startTime", "generation"])
    for t in slot_range:
        w.writerow([iso(t), round(truth[t])])

rows = 0
hourly = [t for t in slot_range if t.minute == 0]           # WINDFOR targets sit on the hour
grid = [datetime.combine(START - timedelta(days=2), time(0), tzinfo=UTC) + timedelta(hours=3 * i)
        for i in range(((END - START).days + 4) * 8)]       # forecasts are issued every few hours
with (OUT / "forecasts.csv").open("w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["startTime", "publishTime", "generation"])
    for t in hourly:
        for p in grid:
            h = (t - p).total_seconds() / 3600
            if 0 <= h <= 48:
                skill = min(1.0, max(0.08, h / 48)) ** 0.8
                err = 1500 * skill * persist[t] + rng.gauss(0, 40 + 6 * h) + 120 * skill   # mild over-forecast bias
                w.writerow([iso(t), iso(p), round(max(0.0, truth[t] + err))])
                rows += 1

(OUT / "meta.json").write_text(json.dumps({
    "synthetic": True, "source": "Generated by scripts/make_sample.py - NOT Elexon data",
    "delivery_start": START.isoformat(), "delivery_end": END.isoformat(),
    "generated_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
}, indent=2))
print(f"wrote {len(slot_range)} actual rows and {rows} forecast rows to {OUT}")
